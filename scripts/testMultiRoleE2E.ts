/**
 * Multi-Role E2E Workflow & Tokenized Activation Verification Suite
 * (PHASE 5: 5-TIER ROLE SCOPING, INVITATION TOKENS, AND COURSE OFFERINGS)
 *
 * Verifies:
 * 1. University Admin & Department Admin scoped access
 * 2. Administrative pre-registration of official student records
 * 3. 7-Day Expiring token generation and one-time activation claim
 * 4. Token redemption creates linked official StudentProfile without identity tampering
 * 5. Expired/revoked/duplicate token rejection
 * 6. Course offerings mapped to academic terms, sections, and assigned course teachers
 * 7. Course teacher section-level scoping (only assigned sections can record attendance/marks)
 * 8. Missing marks remain strictly null (!= 0)
 * 9. Attendance session draft/publish lifecycle with audit correction history
 * 10. Mark modification audit trail with actor, timestamp, old/new value, and reason
 * 11. 5-Tier role security invariant checks
 */

import {
  User,
  StudentProfile,
  Department,
  CourseOffering,
  StudentInvitation,
  AttendanceSession,
  AuditCorrectionRecord,
  AttendanceRecord,
  Mark,
  Assessment,
} from '../src/shared/types';
import { getCurrentUtcIso } from '../src/shared/utils/date';

async function runMultiRoleE2E() {
  console.log('================================================================');
  console.log('🏛️  MULTI-ROLE & TOKENIZED ACTIVATION E2E TEST SUITE');
  console.log('================================================================\n');

  let passed = 0;
  let failed = 0;

  function assert(condition: boolean, msg: string) {
    if (condition) {
      console.log(`  ✅ [PASS] ${msg}`);
      passed++;
    } else {
      console.error(`  ❌ [FAIL] ${msg}`);
      failed++;
    }
  }

  // In-memory store for multi-role test
  const users = new Map<string, User>();
  const profiles = new Map<string, StudentProfile>();
  const departments = new Map<string, Department>();
  const offerings = new Map<string, CourseOffering>();
  const invitations = new Map<string, StudentInvitation>();
  const attendanceSessions = new Map<string, AttendanceSession>();
  const auditCorrections: AuditCorrectionRecord[] = [];
  const marks = new Map<string, Mark>();

  console.log('--- TEST 1: 5-Tier Role & Scoped Hierarchy Provisioning ---');
  // 1. University Admin
  const uniAdmin: User = {
    id: 'usr_uni_admin',
    email: 'admin@baust.edu.bd',
    displayName: 'Prof. University Admin',
    role: 'university_admin',
    createdAt: getCurrentUtcIso(),
    updatedAt: getCurrentUtcIso(),
  };
  users.set(uniAdmin.id, uniAdmin);
  assert(uniAdmin.role === 'university_admin', 'University Admin identity provisioned');

  // 2. Department Admin (CSE)
  const deptAdmin: User = {
    id: 'usr_dept_admin_cse',
    email: 'head.cse@baust.edu.bd',
    displayName: 'Head of CSE',
    role: 'dept_admin',
    departmentId: 'dept_cse',
    assignedDepartment: 'CSE',
    createdAt: getCurrentUtcIso(),
    updatedAt: getCurrentUtcIso(),
  };
  users.set(deptAdmin.id, deptAdmin);
  assert(deptAdmin.role === 'dept_admin' && deptAdmin.assignedDepartment === 'CSE', 'Department Admin scoped to CSE');

  // 3. Course Teacher
  const teacher: User = {
    id: 'usr_teacher_311',
    email: 'teacher.cse311@baust.edu.bd',
    displayName: 'Dr. Database Teacher',
    role: 'teacher',
    assignedDepartment: 'CSE',
    createdAt: getCurrentUtcIso(),
    updatedAt: getCurrentUtcIso(),
  };
  users.set(teacher.id, teacher);
  assert(teacher.role === 'teacher', 'Course Teacher identity provisioned');

  // 4. Faculty Advisor
  const advisor: User = {
    id: 'usr_advisor_01',
    email: 'advisor@baust.edu.bd',
    displayName: 'Faculty Advisor Khan',
    role: 'advisor',
    assignedDepartment: 'CSE',
    advisorSectionIds: ['sec_2026_cse_a'],
    createdAt: getCurrentUtcIso(),
    updatedAt: getCurrentUtcIso(),
  };
  users.set(advisor.id, advisor);
  assert(advisor.role === 'advisor', 'Advisor identity provisioned with section assignment');

  console.log('\n--- TEST 2: Administrative Pre-Registration & Token Generation ---');
  // Dept Admin pre-registers official student
  const tokenRand = 'ABC789';
  const token = `ACT-${tokenRand}-2026TEST`;
  const invitation: StudentInvitation = {
    id: `inv_${token}`,
    token,
    officialStudentId: 'CSE-2026-042',
    email: 'student042@baust.edu.bd',
    department: 'CSE',
    batch: '2026',
    section: 'A',
    level: 'Level 1, Term 1',
    status: 'pending',
    expiresAt: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000).toISOString(),
    createdAt: getCurrentUtcIso(),
    createdBy: deptAdmin.id,
  };
  invitations.set(invitation.token, invitation);
  assert(invitations.has(token), 'Official student invitation generated by Dept Admin');
  assert(invitation.status === 'pending', 'Invitation status initialized to "pending"');
  assert(new Date(invitation.expiresAt).getTime() > Date.now(), 'Token has valid 7-day future expiry');

  console.log('\n--- TEST 3: Expired & Revoked Token Rejection ---');
  // Expired token test
  const expiredToken = 'ACT-EXPIRED-999';
  const expiredInv: StudentInvitation = {
    id: `inv_${expiredToken}`,
    token: expiredToken,
    officialStudentId: 'CSE-2026-999',
    email: 'expired@baust.edu.bd',
    department: 'CSE',
    batch: '2026',
    status: 'pending',
    expiresAt: new Date(Date.now() - 3600 * 1000).toISOString(), // 1 hour ago
    createdAt: getCurrentUtcIso(),
    createdBy: deptAdmin.id,
  };
  invitations.set(expiredToken, expiredInv);

  function verifyTokenMock(t: string): { valid: boolean; reason?: string } {
    const inv = invitations.get(t);
    if (!inv) return { valid: false, reason: 'NOT_FOUND' };
    if (inv.status === 'claimed') return { valid: false, reason: 'ALREADY_CLAIMED' };
    if (inv.status === 'revoked') return { valid: false, reason: 'REVOKED' };
    if (new Date(inv.expiresAt).getTime() < Date.now()) return { valid: false, reason: 'EXPIRED' };
    return { valid: true };
  }

  const expiredCheck = verifyTokenMock(expiredToken);
  assert(!expiredCheck.valid && expiredCheck.reason === 'EXPIRED', 'Expired token correctly rejected');

  // Revocation test
  const revokedToken = 'ACT-REVOKED-111';
  invitations.set(revokedToken, {
    ...invitation,
    token: revokedToken,
    status: 'revoked',
  });
  const revokedCheck = verifyTokenMock(revokedToken);
  assert(!revokedCheck.valid && revokedCheck.reason === 'REVOKED', 'Revoked token correctly rejected');

  console.log('\n--- TEST 4: Student Token Activation & Immutable Profile Linking ---');
  // Student activates account with valid token
  const validCheck = verifyTokenMock(token);
  assert(validCheck.valid, 'Valid token passes verification');

  const studentAuthUid = 'usr_stu_alice';
  const studentUser: User = {
    id: studentAuthUid,
    email: invitation.email,
    displayName: 'Alice Rahman',
    role: 'student',
    createdAt: getCurrentUtcIso(),
    updatedAt: getCurrentUtcIso(),
  };
  users.set(studentAuthUid, studentUser);

  // Link profile from invitation
  const studentProfile: StudentProfile = {
    id: studentAuthUid,
    studentId: invitation.officialStudentId, // Immutable from admin invitation
    userId: studentAuthUid,
    department: invitation.department,
    batch: invitation.batch,
    level: invitation.level,
    currentSemesterId: '2026-spring',
    cgpa: null,
    createdAt: getCurrentUtcIso(),
    updatedAt: getCurrentUtcIso(),
    createdBy: studentAuthUid,
  };
  profiles.set(studentAuthUid, studentProfile);

  // Mark token claimed
  invitation.status = 'claimed';
  invitation.claimedAt = getCurrentUtcIso();
  invitation.claimedByUid = studentAuthUid;

  assert(profiles.get(studentAuthUid)?.studentId === 'CSE-2026-042', 'Profile securely bound to official student ID');
  assert(invitation.status === 'claimed', 'Invitation token transitioned to "claimed"');

  // Second activation attempt must fail (one-time token)
  const secondAttempt = verifyTokenMock(token);
  assert(!secondAttempt.valid && secondAttempt.reason === 'ALREADY_CLAIMED', 'Re-using claimed token is strictly rejected');

  console.log('\n--- TEST 5: Term-Specific Course Offerings & Multi-Faculty Scoping ---');
  const courseOffering: CourseOffering = {
    id: 'off_2026-spring_CSE311_A',
    courseId: 'crs_cse311',
    courseCode: 'CSE311',
    courseTitle: 'Database Management Systems',
    semesterId: '2026-spring',
    section: 'A',
    teacherIds: [teacher.id],
    capacity: 50,
    status: 'active',
    createdAt: getCurrentUtcIso(),
    updatedAt: getCurrentUtcIso(),
    createdBy: deptAdmin.id,
  };
  offerings.set(courseOffering.id, courseOffering);
  assert(offerings.has(courseOffering.id), 'Course offering created with section and assigned faculty');

  // Scoping check: Teacher assigned to CSE311 Section A can manage it
  const isAssigned = courseOffering.teacherIds.includes(teacher.id);
  assert(isAssigned, 'Teacher is authorized for assigned course offering');

  // Unassigned teacher check
  const otherTeacherId = 'usr_teacher_other';
  const isOtherAssigned = courseOffering.teacherIds.includes(otherTeacherId);
  assert(!isOtherAssigned, 'Non-assigned teacher is restricted from managing section');

  console.log('\n--- TEST 6: Attendance Draft vs Published Lifecycle & Audit Corrections ---');
  // Draft session
  const session: AttendanceSession = {
    id: 'att_sess_2026-02-10_A',
    courseOfferingId: courseOffering.id,
    courseId: 'crs_cse311',
    semesterId: '2026-spring',
    section: 'A',
    date: '2026-02-10',
    teacherId: teacher.id,
    status: 'draft',
    createdAt: getCurrentUtcIso(),
    updatedAt: getCurrentUtcIso(),
  };
  attendanceSessions.set(session.id, session);
  assert(session.status === 'draft', 'Attendance session created in draft status');

  // Publish session
  session.status = 'published';
  session.publishedAt = getCurrentUtcIso();
  assert(session.status === 'published' && session.publishedAt !== undefined, 'Attendance session published after validation');

  // Correction with audit history
  const attCorrection: AuditCorrectionRecord = {
    id: 'aud_att_001',
    entityType: 'attendance',
    recordId: 'rec_att_alice_2026-02-10',
    field: 'status',
    oldValue: 'absent',
    newValue: 'present',
    reason: 'Student arrived late due to university bus breakdown; verified by transportation office.',
    actorUid: teacher.id,
    timestamp: getCurrentUtcIso(),
  };
  auditCorrections.push(attCorrection);
  assert(auditCorrections.length === 1, 'Attendance correction logged in append-only audit trail');
  assert(auditCorrections[0].reason.includes('bus breakdown'), 'Audit correction preserves justification reason');

  console.log('\n--- TEST 7: Assessment & Mark Entry with Strict Null Semantics ---');
  const midtermAsmt: Assessment = {
    id: 'asmt_midterm_cse311',
    courseId: 'crs_cse311',
    semesterId: '2026-spring',
    title: 'Midterm Examination',
    type: 'midterm',
    maxMarks: 50,
    weightage: 25,
    dueDate: '2026-03-15T10:00:00.000Z',
    createdAt: getCurrentUtcIso(),
    updatedAt: getCurrentUtcIso(),
    createdBy: teacher.id,
  };

  // Ungraded mark must be null (not 0)
  const unrecordedMark: Mark = {
    id: 'mrk_alice_midterm',
    assessmentId: midtermAsmt.id,
    studentId: studentAuthUid,
    enrollmentId: 'enr_alice_cse311',
    obtainedMarks: null, // Strictly null
    submittedAt: null,
    gradedAt: null,
    createdAt: getCurrentUtcIso(),
    updatedAt: getCurrentUtcIso(),
    createdBy: teacher.id,
  };
  marks.set(unrecordedMark.id, unrecordedMark);
  assert(unrecordedMark.obtainedMarks === null, 'Ungraded mark strictly stored as null');
  assert(unrecordedMark.obtainedMarks !== 0, 'Ungraded mark is never coerced to 0');

  // Grade entered: 44/50
  unrecordedMark.obtainedMarks = 44;
  unrecordedMark.gradedAt = getCurrentUtcIso();
  assert(unrecordedMark.obtainedMarks === 44, 'Obtained mark persisted correctly');

  // Mark correction audit
  const markCorrection: AuditCorrectionRecord = {
    id: 'aud_mrk_001',
    entityType: 'mark',
    recordId: unrecordedMark.id,
    field: 'obtainedMarks',
    oldValue: 40,
    newValue: 44,
    reason: 'Re-evaluation of question 3 subpart (b); calculation error corrected.',
    actorUid: teacher.id,
    timestamp: getCurrentUtcIso(),
  };
  auditCorrections.push(markCorrection);
  assert(auditCorrections.length === 2, 'Mark correction logged in audit trail');

  console.log('\n--- TEST 8: Security Role Boundary Invariants ---');
  // Student cannot write to department
  function canWriteDepartment(u: User): boolean {
    return u.role === 'admin' || u.role === 'university_admin';
  }
  assert(!canWriteDepartment(studentUser), 'Student cannot modify department records');
  assert(canWriteDepartment(uniAdmin), 'University Admin can manage department records');

  // Teacher cannot elevate role
  function canModifyUserRole(u: User): boolean {
    return u.role === 'admin' || u.role === 'university_admin';
  }
  assert(!canModifyUserRole(teacher), 'Course Teacher cannot modify user roles');
  assert(!canModifyUserRole(studentUser), 'Student cannot elevate user role');
  assert(canModifyUserRole(uniAdmin), 'University Admin is authorized to manage user roles');

  console.log('\n================================================================');
  console.log(`🏁 MULTI-ROLE & ACTIVATION E2E RESULT: ${passed} PASSED, ${failed} FAILED`);
  console.log('================================================================\n');

  if (failed > 0) {
    process.exit(1);
  }
}

runMultiRoleE2E().catch((err) => {
  console.error('MultiRole E2E suite crashed:', err);
  process.exit(1);
});
